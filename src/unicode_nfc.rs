fn in_category_ranges(ch: char, ranges: &[(u32, u32)]) -> bool {
    let cp = ch as u32;
    let i = ranges.partition_point(|&(start, _)| start <= cp);
    i > 0 && cp <= ranges[i - 1].1
}

/// Unicode general category `L`, matching the tokenizer regex engine.
