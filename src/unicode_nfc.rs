fn canonical_class(cp: u32) -> u8 {
    let i = CCC_RANGES.partition_point(|&(start, _, _)| start <= cp);
    if i == 0 {
        return 0;
    }
    let (start, end, class) = CCC_RANGES[i - 1];
    if cp >= start && cp <= end { class } else { 0 }
}

fn decompose(cp: u32, out: &mut Vec<u32>) {
    let s_index = cp.wrapping_sub(S_BASE);
    if s_index < S_COUNT {
        let l = L_BASE + s_index / N_COUNT;
        let v = V_BASE + (s_index % N_COUNT) / T_COUNT;
        let t = s_index % T_COUNT;
        out.push(l);
        out.push(v);
        if t != 0 {
            out.push(T_BASE + t);
        }
        return;
    }
    if let Ok(i) = DECOMP_INDEX.binary_search_by_key(&cp, |&(key, _, _)| key) {
        let (_, start, len) = DECOMP_INDEX[i];
        for &part in &DECOMP_DATA[start as usize..start as usize + len as usize] {
            decompose(part, out);
        }
    } else {
        out.push(cp);
    }
}

fn compose_pair(left: u32, right: u32) -> Option<u32> {
    let l_index = left.wrapping_sub(L_BASE);
    let v_index = right.wrapping_sub(V_BASE);
    if l_index < L_COUNT && v_index < V_COUNT {
        return Some(S_BASE + (l_index * V_COUNT + v_index) * T_COUNT);
    }
    let s_index = left.wrapping_sub(S_BASE);
    let t_index = right.wrapping_sub(T_BASE);
    if s_index < S_COUNT && s_index % T_COUNT == 0 && (1..T_COUNT).contains(&t_index) {
        return Some(left + t_index);
    }
    let key = ((left as u64) << 21) | right as u64;
    static MAP: std::sync::OnceLock<std::collections::HashMap<u64, u32>> =
        std::sync::OnceLock::new();
    MAP.get_or_init(|| COMPOSITION.iter().copied().collect())
        .get(&key)
        .copied()
}

/// Returns the canonical NFC form of the input text.
pub fn normalize_nfc(text: &str) -> String {
    if text.is_ascii() {
        return text.to_string();
    }
    let mut decomposed = Vec::with_capacity(text.chars().count());
    for ch in text.chars() {
        decompose(ch as u32, &mut decomposed);
    }

    // Stable canonical ordering within every starter segment.
    for i in 1..decomposed.len() {
        let class = canonical_class(decomposed[i]);
        if class == 0 {
            continue;
        }
        let mut j = i;
        while j > 0 {
            let before = canonical_class(decomposed[j - 1]);
            if before == 0 || before <= class {
                break;
            }
            decomposed.swap(j - 1, j);
            j -= 1;
        }
    }
    let Some(&first) = decomposed.first() else {
        return String::new();
    };

    let mut composed = Vec::with_capacity(decomposed.len());
    composed.push(first);
    let mut starter_pos = 0usize;
    let mut starter = first;
    let mut last_class = 0u8;
    for &ch in &decomposed[1..] {
        let class = canonical_class(ch);
        if let Some(value) = compose_pair(starter, ch)
            .filter(|_| last_class == 0 || last_class < class)
        {
            composed[starter_pos] = value;
            starter = value;
        } else {
            if class == 0 {
                starter_pos = composed.len();
                starter = ch;
            }
            composed.push(ch);
            last_class = class;
        }
    }
    composed
        .into_iter()
        .map(|cp| char::from_u32(cp).expect("NFC table produced an invalid scalar"))
        .collect()
}

